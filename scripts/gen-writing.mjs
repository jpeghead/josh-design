// Extracts the PORTED essays from the Framer blog export into a typed module.
// Triage: only essays in PORT are surfaced. AI listicles stay parked.
import { readFileSync, writeFileSync } from "node:fs"

const PORT = ["do-i-still-care-about-this"] // the voice of the whole site

const j = JSON.parse(readFileSync("public/framer/cms/blog/_content.json", "utf8"))
const val = (f) => (f && (f.value ?? null))
const web = (l) => (l ? l.replace(/^public/, "") : null)

const essays = j.items
  .filter((it) => PORT.includes(it.slug))
  .map((it) => {
    const f = it.fields
    return {
      slug: it.slug,
      title: (val(f.Title) || "").trim(),
      date: val(f.Date) || null,
      badge: val(f.Badge) || null,
      description: val(f.Description) || "",
      image: web(f.Image?.local),
      html: val(f.Content) || "",
    }
  })

const banner = `// AUTO-GENERATED by scripts/gen-writing.mjs from the Framer blog export. Do not edit by hand.\n`
const body =
  `export type Essay = {\n  slug: string\n  title: string\n  date: string | null\n  badge: string | null\n  description: string\n  image: string | null\n  html: string\n}\n\n` +
  `export const portedEssays: Essay[] = ${JSON.stringify(essays, null, 2)}\n`

writeFileSync("src/content/writing.generated.ts", banner + body)
console.log(`wrote src/content/writing.generated.ts — ${essays.length} ported essay(s): ${essays.map((e) => e.slug).join(", ")}`)
