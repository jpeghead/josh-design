// Generates src/content/uses.generated.ts from the Framer CMS export.
// Aggregates tools + gear + links + figma-plugins into one typed dataset for /uses.
// Re-run after a fresh framer-pull: node scripts/gen-uses.mjs
import { readFileSync, writeFileSync } from "node:fs"

const COLLECTIONS = [
  { key: "tools", label: "Tools", imageField: "Icon", descField: "Description" },
  { key: "gear", label: "Gear", imageField: "Image", descField: "Description" },
  { key: "figma-plugins", label: "Figma plugins", imageField: "Image", descField: "Content" },
  { key: "links", label: "Links", imageField: "Image", descField: "Content" },
]

const stripHtml = (s) =>
  String(s || "").replace(/<[^>]+>/g, " ").replace(/&amp;/g, "&").replace(/&[a-z]+;/g, " ").replace(/\s+/g, " ").trim()

const webPath = (local) => (local ? local.replace(/^public/, "") : null)
const val = (f) => (f && (f.value ?? null))

const out = []
for (const c of COLLECTIONS) {
  const j = JSON.parse(readFileSync(`public/framer/cms/${c.key}/_content.json`, "utf8"))
  for (const it of j.items) {
    const f = it.fields
    const title = val(f.Title) || it.slug
    const desc = stripHtml(val(f[c.descField]))
    out.push({
      collection: c.key,
      group: c.label,
      title,
      description: desc.length > 200 ? desc.slice(0, 197) + "…" : desc,
      tag: val(f.Tag) || c.label,
      link: val(f.Link) || null,
      image: webPath(f[c.imageField]?.local),
      featured: !!val(f.Featured),
    })
  }
}

const banner = `// AUTO-GENERATED by scripts/gen-uses.mjs from the Framer CMS export. Do not edit by hand.\n`
const body =
  `export type UseItem = {\n` +
  `  collection: "tools" | "gear" | "figma-plugins" | "links"\n` +
  `  group: string\n  title: string\n  description: string\n  tag: string\n` +
  `  link: string | null\n  image: string | null\n  featured: boolean\n}\n\n` +
  `export const uses: UseItem[] = ${JSON.stringify(out, null, 2)}\n`

writeFileSync("src/content/uses.generated.ts", banner + body)
console.log(`wrote src/content/uses.generated.ts — ${out.length} items (${COLLECTIONS.map((c) => c.key + ":" + out.filter((o) => o.collection === c.key).length).join(", ")})`)
